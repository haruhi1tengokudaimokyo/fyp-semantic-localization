"""CPU-only, post-hoc audit of frozen SPVLoc predictions; never selects models."""
import argparse
import csv
import hashlib
import json
import pickle
from pathlib import Path

import numpy as np


def write_csv(path, rows):
    with path.open('w', newline='') as f:
        w = csv.DictWriter(f, fieldnames=list(rows[0]))
        w.writeheader()
        w.writerows(rows)


def main():
    p = argparse.ArgumentParser()
    p.add_argument('--run', type=Path, required=True)
    p.add_argument('--output', type=Path, required=True)
    p.add_argument('--cache', type=Path, required=True)
    a = p.parse_args()
    a.output.mkdir(parents=True, exist_ok=True)
    labels = ['official_zero_shot', 'finetuned']
    keys = ['initial_estimates', 'refined_estimates']
    gt = {int(p.stem.rsplit('_', 1)[1]): json.loads(p.read_text())['poses']
          for p in a.run.glob('offline_evaluation_gt_*.json')}
    refs = {}
    for sid in sorted(gt):
        # Trusted local cache generated by this run, not downloaded pickle input.
        with (a.cache / f'temp_{sid:05d}_ps1200_ch1400_ns1_rad1400_h300').open('rb') as f:
            b = pickle.load(f)
        refs[sid] = int(b['sampled_semantics'].shape[0])
        assert refs[sid] == len(b['sampled_poses']) == len(b['combined_poses'])
        del b
    all_rows, query_sets, summaries, scenes = [], {}, {}, []

    def aggregate(rows):
        t = np.array([x['translation_m'] for x in rows])
        r = np.array([x['rotation_deg'] for x in rows])
        xy = np.array([x['xy_translation_m'] for x in rows])
        return dict(queries=len(rows), translation_median_m=float(np.median(t)),
                    translation_mean_m=float(t.mean()), translation_rmse_m=float(np.sqrt(np.mean(t*t))),
                    translation_p90_m=float(np.quantile(t, .9)), translation_p95_m=float(np.quantile(t, .95)),
                    rotation_median_deg=float(np.median(r)), rotation_p90_deg=float(np.quantile(r, .9)),
                    xy_translation_median_m=float(np.median(xy)),
                    success_10cm5deg=float(np.mean((t < .1) & (r < 5))),
                    success_50cm10deg=float(np.mean((t < .5) & (r < 10))),
                    success_1m30deg=float(np.mean((t < 1) & (r < 30))),
                    success_5m30deg=float(np.mean((t < 5) & (r < 30))),
                    translation_only_1m=float(np.mean(t < 1)), rotation_only_30deg=float(np.mean(r < 30)),
                    fail_translation_only=int(np.sum((t >= 1) & (r < 30))),
                    fail_rotation_only=int(np.sum((t < 1) & (r >= 30))),
                    fail_both=int(np.sum((t >= 1) & (r >= 30))))

    for label in labels:
        saved = json.loads((a.run / f'metrics_{label}.json').read_text())
        independent = json.loads((a.run / f'independent_metrics_{label}.json').read_text())
        assert independent['status'] == 'INDEPENDENT_POSE_METRICS_ACCEPTED'
        seen, rows, seconds = set(), [], []
        for path in sorted(a.run.glob(f'eval_{label}_*.json')):
            x = json.loads(path.read_text())
            sid, qi = x['scene_id'], x['query_index']
            assert (sid, qi) not in seen and x['GT_offline_only']
            seen.add((sid, qi))
            truth = np.array(gt[sid][qi], dtype=float)
            seconds.append(x['seconds'])
            for key in keys:
                pred = np.array(x['estimates'][key]['pose'], dtype=float)
                d = (pred[:3, 3] - truth[:3, 3]) / 1000
                te = float(np.linalg.norm(d))
                re = float(np.degrees(np.arccos(np.clip((np.sum(pred[:3, :3]*truth[:3, :3])-1)/2, -1, 1))))
                assert np.isfinite(pred).all()
                assert abs(te - x['estimates'][key]['translation_error_m']) < 1e-6
                assert abs(re - x['estimates'][key]['rotation_error_deg']) < 1e-4
                rows.append(dict(model=label, stage=key, scene_id=sid, query_index=qi,
                                 translation_m=te, xy_translation_m=float(np.linalg.norm(d[:2])),
                                 rotation_deg=re, success_1m30deg=bool(te < 1 and re < 30),
                                 both_stages_seconds=x['seconds'], reference_count=refs[sid]))
        assert len(seen) == saved['queries'] == 2752
        query_sets[label] = seen
        summaries[label] = {}
        for key in keys:
            sub = [x for x in rows if x['stage'] == key]
            z = aggregate(sub)
            for m in ['translation_median_m', 'rotation_median_deg', 'success_1m30deg']:
                assert abs(z[m] - saved['metrics'][key][m]) < 1e-4
            per = []
            for sid in sorted(gt):
                s = aggregate([x for x in sub if x['scene_id'] == sid])
                scenes.append(dict(model=label, stage=key, scene_id=sid, **s))
                per.append(s['success_1m30deg'])
            z['macro_building_success_1m30deg'] = float(np.mean(per))
            summaries[label][key] = z
        summaries[label]['timing'] = dict(mean_seconds=float(np.mean(seconds)),
                                         median_seconds=float(np.median(seconds)), p95_seconds=float(np.quantile(seconds, .95)),
                                         sum_query_seconds=float(sum(seconds)), includes_refinement=True,
                                         includes_reencoding_reference_features=True, excludes_map_preparation=True)
        initial = [x for x in rows if x['stage'] == keys[0]]
        refined = [x for x in rows if x['stage'] == keys[1]]
        summaries[label]['refinement_changes'] = dict(
            failure_to_success=sum(not x['success_1m30deg'] and y['success_1m30deg'] for x, y in zip(initial, refined)),
            success_to_failure=sum(x['success_1m30deg'] and not y['success_1m30deg'] for x, y in zip(initial, refined)),
            translation_improved=sum(y['translation_m'] < x['translation_m'] for x, y in zip(initial, refined)))
        all_rows.extend(rows)
    assert query_sets[labels[0]] == query_sets[labels[1]]
    metrics = list(csv.DictReader((a.run / 'loss_logs/version_0/metrics.csv').open()))
    assert all(np.isfinite(float(v)) for row in metrics for v in row.values() if v)
    epoch_rows = []
    for row in metrics:
        if row['validation/loss_epoch']:
            epoch_rows.append(dict(epoch=int(float(row['epoch']))+1, optimizer_step=int(float(row['step']))+1,
                **{k.removeprefix('validation/').removesuffix('_epoch'): float(v)
                   for k, v in row.items() if k.startswith('validation/') and k.endswith('_epoch') and v}))
    assert len(epoch_rows) == 25
    write_csv(a.output / 'validation_epochs.csv', epoch_rows)
    write_csv(a.output / 'per_query_metrics.csv', all_rows)
    write_csv(a.output / 'per_building_metrics.csv', scenes)
    e = json.loads((a.run / 'training_evidence.json').read_text())
    progress = json.loads((a.run / 'training_progress.json').read_text())
    final = dict(status='TRAINING_AND_PAIRED_HELDOUT_EVALUATION_VERIFIED',
                 models=summaries, test_buildings=20, identical_query_sets=True,
                 metrics_scope='3D Euclidean translation and full orientation; strict thresholds; additional thresholds are post-hoc descriptive statistics',
                 reference_counts=refs,
                 reference_recording_correction='Original per-query reference_count used dummy depth length=1; actual semantic map reference counts verified from cache. Predictions unchanged.',
                 training={k: v for k, v in e.items() if k not in ['updated_tensors', 'status']},
                 elapsed_training_seconds=progress['elapsed_training_seconds'],
                 original_filter_valid_fraction=progress['original_filter_valid_fraction'],
                 validation_first=epoch_rows[0], validation_last=epoch_rows[-1],
                 test_used_for_checkpoint_selection=False)
    (a.output / 'summary.json').write_text(json.dumps(final, indent=2))
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt
    fig, ax = plt.subplots(1, 3, figsize=(14, 4))
    for col, title, axis in zip(['loss_decode_semantics', 'loss_decode_layout', 'loss'],
                                 ['Validation semantic CE', 'Validation normal cosine loss', 'Validation total loss'], ax):
        axis.plot([x['epoch'] for x in epoch_rows], [x[col] for x in epoch_rows], marker='.')
        axis.axvline(19, color='gray', linestyle='--', label='Selected epoch 19')
        axis.set(xlabel='Epoch', title=title)
        axis.grid(alpha=.25)
    ax[0].legend()
    fig.tight_layout(); fig.savefig(a.output / 'validation_curves.png', dpi=160); plt.close(fig)
    fig, ax = plt.subplots(1, 2, figsize=(11, 4))
    for label in labels:
        t = sorted(x['translation_m'] for x in all_rows if x['model'] == label and x['stage'] == 'refined_estimates')
        ax[0].plot(t, np.arange(1, len(t)+1)/len(t), label=label)
        v = [x for x in scenes if x['model'] == label and x['stage'] == 'refined_estimates']
        ax[1].plot([str(x['scene_id']) for x in v], [100*x['success_1m30deg'] for x in v], marker='.', label=label)
    ax[0].set(xlabel='3D translation error (m)', ylabel='Fraction', xlim=(0, 15), title='Refined translation error CDF')
    ax[1].set(xlabel='Held-out building', ylabel='Success (%) at <1m and <30deg', title='Per-building refined localization')
    ax[1].tick_params(axis='x', rotation=90)
    for z in ax: z.grid(alpha=.25); z.legend()
    fig.tight_layout(); fig.savefig(a.output / 'localization_results.png', dpi=160); plt.close(fig)
    print(json.dumps({k: v for k, v in final.items() if k not in ['reference_counts', 'training']}, indent=2))


if __name__ == '__main__':
    main()
